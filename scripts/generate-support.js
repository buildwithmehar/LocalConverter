import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { getRegistry } from '../server/conversion/index.js';

const registry = await getRegistry();
const labels = Object.fromEntries(registry.formats.map((f) => [f.id, f.label]));
const rows = registry.formats
  .map((format) => {
    const targets = registry.pairs
      .filter((p) => p.source === format.id)
      .map((p) => p.target.toUpperCase());
    return targets.length ? `| ${format.label} (${format.id}) | ${targets.join(', ')} |` : '';
  })
  .filter(Boolean);
const engineRows = [...new Set(registry.pairs.map((p) => p.engine))].map((engine) => {
  const limitations = [
    ...new Set(registry.pairs.filter((p) => p.engine === engine).flatMap((p) => p.limitations)),
  ];
  return `### ${engine}\n\n${limitations.map((x) => `- ${x}`).join('\n')}`;
});
const content = `# Supported local formats

Generated by \`node scripts/generate-support.js\` from the live engine registry.
This installation advertises **${registry.pairs.length} conversion pairs across ${registry.formats.length} formats**, plus **${registry.tools.length} dedicated toolbox pages**.
FFmpeg pairs appear only when FFmpeg and FFprobe are detected, with the required encoder available. ZIP/7Z/TAR repacking appears only when the local 7-Zip executable is detected. Same-format raster pairs provide resize and re-encoding options.
The running website's registry is authoritative if installed dependencies change.

| Input | Available outputs |
| --- | --- |
${rows.join('\n')}

## Installed capabilities

${registry.dependencies.map((d) => `- **${d.name}**: ${d.available ? 'available' : 'unavailable'}${d.version ? ` (${d.version})` : ''}${d.reason ? `. ${d.reason}` : ''}`).join('\n')}

## Limits and behavior

- Inputs must match the selected format. Text inputs use UTF-8; binary null characters are rejected.
- Input limit: 100 MB. Output limit: 200 MB. Images/rendered pages: 40 million pixels. PDF: 100 pages and 100 million total rendered pixels.
- One final artifact is returned per conversion. Multiple PDF image pages become a ZIP; selecting one page produces one image.
- ZIPs support stored/Deflate entries with UTF-8 names; ZIP64, encryption, split archives, duplicate paths and unsafe names are rejected. ZIP/GZIP checksums are verified. Expansion is limited to 100 MB and 1,000 archive entries. ZIP/7Z/TAR repacking uses bounded member pipes, rejects links and special entries, and does not retain permissions or timestamps.
- Width, quality, PDF page/scale, media trim/bitrate/quality and GIF frame-rate controls are shown only where implemented. Media start/duration use whole seconds; duration 0 uses the remainder.
- No network conversion services, remote resource loading or URL inputs. SVG inputs must be self-contained, without CSS escape sequences. HTML/Markdown are converted to simple text flow, without loading resources.
- Media subprocesses use explicit demuxers, the file/pipe protocol whitelist, a 180 second deadline, bounded output, and cancellation. Missing FFmpeg removes media pairs.
- Native parsers run as the current OS user in a separate job process. This is process isolation with limits, not a hardened hostile-file sandbox.
- Dedicated toolbox pages add Office layout rendering, English OCR, ebooks, font containers, camera RAW and more. CAD/3D and exact PDF-to-Word reconstruction remain unsupported. No engine downloads dependencies during conversion.
- Exact document layout and arbitrary Unicode typography are not promised by the built-in Latin PDF fonts. DOCX extraction produces semantic text/HTML.
- CSV/TSV exports preserve string fields, including leading zeros. Spreadsheet applications may interpret leading formula characters on opening a CSV; this converter preserves the underlying values.

## Dedicated toolbox pages

Each tool has its own settings and explicit limits. See [toolbox.md](toolbox.md) for the 70-family coverage and runtime setup.

| Tool | Category | Accepts | Limitation |
|---|---|---|---|
${registry.tools.map((t) => `| [${t.title}](http://127.0.0.1:3000/${t.id}) | ${t.category} | ${t.accept.join(', ')} | ${t.note.replaceAll('|', '/')} |`).join('\n')}

## Engine-specific limitations

${engineRows.join('\n\n')}

## Verification

Run \`node --test tests/conversion.test.js\` for a generated fixture corpus that exercises every advertised pair and decodes each output. The corpus includes binary image/PDF decoding, media metadata/duration checks, data string preservation, quality/resize/trim controls, archive checksums and expansion limits, unsafe SVG, corrupt files, input/page caps and cancellation cleanup.

## Technical references

- [Sharp output formats](https://sharp.pixelplumbing.com/api-output/) and [input pixel limits](https://sharp.pixelplumbing.com/api-constructor/).
- [7-Zip supported formats and source](https://www.7-zip.org/) and [licensing](https://www.7-zip.org/faq.html).
- [FFmpeg protocol whitelist](https://ffmpeg.org/ffmpeg-protocols.html).
- [PDF.js project](https://mozilla.github.io/pdf.js/).
- [Mammoth semantic DOCX conversion](https://github.com/mwilliamson/mammoth.js).
`;
await fs.writeFile(
  fileURLToPath(new URL('../docs/supported-formats.md', import.meta.url)),
  content,
);
console.log(
  `Documented ${registry.pairs.length} verified-capability pairs across ${Object.keys(labels).length} formats.`,
);
